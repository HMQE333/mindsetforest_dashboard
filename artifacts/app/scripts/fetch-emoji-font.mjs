// Emoji as on Windows 11 on every device: Microsoft's Fluent Emoji (the
// "Color" style, MIT) as a webfont split into 129 unicode-range subsets
// (tetunori/fluent-emoji-webfont, MIT), so a page only downloads the subsets
// holding the emoji it shows.
//
// Writes public/fonts/fluent-emoji/fluent-emoji.css (committed) and downloads
// the .woff2 subsets next to it (git-ignored, 37 MB) before a build. Each
// @font-face lists the self-hosted file first and the original second, so a
// dev server without the files still shows Fluent emoji. Digits, # and *,
// (c), (R), TM, i and the arrows are left out of the ranges: the font has
// glyphs for them (keycaps, text-style symbols) and they must stay text.
//
// Run by "prebuild" and "preview:build"; `pnpm fonts:emoji` on its own.
// Offline it keeps whatever is already there and the build goes on.
import { existsSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const REMOTE = "https://tetunori.github.io/fluent-emoji-webfont/dist/";
const FAMILY = "Fluent Emoji Color";
const here = fileURLToPath(new URL(".", import.meta.url));
const outDir = join(here, "..", "public", "fonts", "fluent-emoji");
const cssPath = join(outDir, "fluent-emoji.css");

const TEXT_CODEPOINTS = new Set([0x23, 0x2a, ...Array.from({ length: 10 }, (_, i) => 0x30 + i), 0xa9, 0xae, 0x2122, 0x2139]);
const isText = (cp) => TEXT_CODEPOINTS.has(cp) || (cp >= 0x2190 && cp <= 0x21ff);

/** "U+1f600-1f64f, U+23, U+2764" without the code points that must stay text. */
export function filterRange(range) {
  const out = [];
  for (const tok of range.split(",").map((t) => t.trim()).filter(Boolean)) {
    const [a, b] = tok.slice(2).split("-").map((h) => parseInt(h, 16));
    if (b === undefined) {
      if (!isText(a)) out.push(tok);
      continue;
    }
    // Ranges in the source never straddle the text code points; drop one that is all text.
    let keep = false;
    for (let cp = a; cp <= b && !keep; cp++) keep = !isText(cp);
    if (keep) out.push(tok);
  }
  return [...new Set(out)].join(", ");
}

async function download(file) {
  const target = join(outDir, file);
  if (existsSync(target)) return true;
  try {
    const resp = await fetch(REMOTE + file);
    if (!resp.ok) return false;
    writeFileSync(target, Buffer.from(await resp.arrayBuffer()));
    return true;
  } catch {
    return false;
  }
}

async function main() {
  mkdirSync(outDir, { recursive: true });
  let source;
  try {
    const resp = await fetch(REMOTE + "FluentEmojiColor.css");
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    source = await resp.text();
  } catch (e) {
    console.warn(`fetch-emoji-font: offline (${e.message}); keeping ${existsSync(cssPath) ? "the existing files" : "system emoji"}`);
    return;
  }

  const faces = [...source.matchAll(/url\('[^']*\/(FluentEmojiColor\d+\.woff2)'\)[^;]*;\s*unicode-range:\s*([^;]+);/g)].map((m) => ({
    file: m[1],
    range: filterRange(m[2]),
  }));
  if (faces.length === 0) {
    console.warn("fetch-emoji-font: the stylesheet changed shape; nothing written");
    return;
  }

  // Eight at a time: polite to the host, still quick.
  const files = [...new Set(faces.map((f) => f.file))];
  let ok = 0;
  for (let i = 0; i < files.length; i += 8) {
    const got = await Promise.all(files.slice(i, i + 8).map(download));
    ok += got.filter(Boolean).length;
  }

  const css = faces
    .filter((f) => f.range)
    .map(
      (f) => `@font-face {
  font-family: '${FAMILY}';
  font-display: swap;
  src: url('./${f.file}') format('woff2'), url('${REMOTE}${f.file}') format('woff2');
  unicode-range: ${f.range};
}`,
    )
    .join("\n");
  const header = `/* Fluent Emoji (Microsoft, MIT) as a webfont (tetunori/fluent-emoji-webfont, MIT).\n   Generated by scripts/fetch-emoji-font.mjs; do not edit. */\n`;
  const next = header + css + "\n";
  if (!existsSync(cssPath) || readFileSync(cssPath, "utf8") !== next) writeFileSync(cssPath, next);
  console.log(`fetch-emoji-font: ${faces.length} subsets, ${ok}/${files.length} files in public/fonts/fluent-emoji`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
