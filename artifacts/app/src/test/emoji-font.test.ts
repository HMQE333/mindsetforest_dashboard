import { describe, it, expect } from "vitest";
import { facesForText, parseEmojiFaces, parseUnicodeRange } from "../lib/emoji-font";

// Two rules in the shape scripts/fetch-emoji-font.mjs writes.
const CSS = `/* Fluent Emoji (Microsoft, MIT) as a webfont (tetunori/fluent-emoji-webfont, MIT).
   Generated by scripts/fetch-emoji-font.mjs; do not edit. */
@font-face {
  font-family: 'Fluent Emoji Color';
  font-display: swap;
  src: url('./FluentEmojiColor128.woff2') format('woff2'), url('https://tetunori.github.io/fluent-emoji-webfont/dist/FluentEmojiColor128.woff2') format('woff2');
  unicode-range: U+3299;
}
@font-face {
  font-family: 'Fluent Emoji Color';
  font-display: swap;
  src: url('./FluentEmojiColor011.woff2') format('woff2'), url('https://tetunori.github.io/fluent-emoji-webfont/dist/FluentEmojiColor011.woff2') format('woff2');
  unicode-range: U+1f3ae, U+1f4ca-1f4cb, U+2764;
}
`;
const BASE = "https://app.example/fonts/fluent-emoji/fluent-emoji.css";

describe("emoji font loader", () => {
  it("parses single code points and ranges", () => {
    expect(parseUnicodeRange("U+3299")).toEqual([[0x3299, 0x3299]]);
    expect(parseUnicodeRange("U+1f3ae, U+1f4ca-1f4cb ,U+2764")).toEqual([
      [0x1f3ae, 0x1f3ae],
      [0x1f4ca, 0x1f4cb],
      [0x2764, 0x2764],
    ]);
    expect(parseUnicodeRange("")).toEqual([]);
  });

  it("reads every @font-face and makes its files absolute against the stylesheet", () => {
    const faces = parseEmojiFaces(CSS, BASE);
    expect(faces).toHaveLength(2);
    expect(faces[0].src).toBe(
      "url('https://app.example/fonts/fluent-emoji/FluentEmojiColor128.woff2') format('woff2'), " +
        "url('https://tetunori.github.io/fluent-emoji-webfont/dist/FluentEmojiColor128.woff2') format('woff2')",
    );
    expect(faces[1].unicodeRange).toBe("U+1f3ae, U+1f4ca-1f4cb, U+2764");
  });

  it("works under a relative base path (preview builds)", () => {
    const faces = parseEmojiFaces(CSS, "https://host.example/some/preview/fonts/fluent-emoji/fluent-emoji.css");
    expect(faces[0].src).toContain("url('https://host.example/some/preview/fonts/fluent-emoji/FluentEmojiColor128.woff2')");
  });

  it("picks only the faces that hold a character on the page", () => {
    const faces = parseEmojiFaces(CSS, BASE);
    expect(facesForText(faces, "🎮 Home  📊 Stats")).toEqual([faces[1]]);
    expect(facesForText(faces, "㊙")).toEqual([faces[0]]);
    // Plain and Polish text, punctuation: no emoji subset.
    expect(facesForText(faces, "Wykłady — zbiór… Sign in")).toEqual([]);
  });

  it("takes only the rule defined last when one emoji is in several subsets", () => {
    const overlapping = parseEmojiFaces(
      `@font-face { src: url('./A.woff2'); unicode-range: U+1f373, U+1f600; }
       @font-face { src: url('./B.woff2'); unicode-range: U+1f373; }`,
      BASE,
    );
    expect(facesForText(overlapping, "🍳").map((f) => f.src)).toEqual(["url('https://app.example/fonts/fluent-emoji/B.woff2')"]);
    expect(facesForText(overlapping, "🍳😀")).toHaveLength(2);
  });
});
